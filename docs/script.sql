-- G05 - Quais sinistros estão em acompanhamento?
-- Atende: P5; RF18
SELECT s.id_sinistro,a.numero_apolice,s.data_sinistro,s.status,s.descricao FROM sinistro s JOIN apolice a ON a.id_apolice=s.id_apolice WHERE s.status<>'Encerrado' ORDER BY s.data_sinistro;

-- G06 - Quantos atendimentos e visitas foram registrados por mês?
-- Atende: P6; KPI1; RF16
SELECT DATE_FORMAT(data_atendimento,'%Y-%m') AS mes,tipo_atendimento,COUNT(*) AS quantidade FROM atendimento WHERE data_atendimento>=@inicio AND data_atendimento<@fim_exclusivo GROUP BY mes,tipo_atendimento ORDER BY mes,tipo_atendimento;

-- G07 - Qual a taxa de conversão das cotações de cada mês em contratação até a data de referência?
-- Atende: KPI2
SELECT DATE_FORMAT(q.data_cotacao,'%Y-%m') AS mes,COUNT(*) AS cotacoes, SUM(EXISTS(SELECT 1 FROM proposta p JOIN apolice a ON a.id_proposta=p.id_proposta WHERE p.id_cotacao=q.id_cotacao AND a.inicio_vigencia<=@data_referencia)) AS cotacoes_convertidas, ROUND(100.0*SUM(EXISTS(SELECT 1 FROM proposta p JOIN apolice a ON a.id_proposta=p.id_proposta WHERE p.id_cotacao=q.id_cotacao AND a.inicio_vigencia<=@data_referencia))/NULLIF(COUNT(*),0),2) AS taxa_percentual FROM cotacao q WHERE q.data_cotacao>=@inicio AND q.data_cotacao<@fim_exclusivo AND q.data_cotacao<=@data_referencia GROUP BY mes ORDER BY mes;

-- G08 - Qual percentual do valor vencido permanece sem pagamento na data de referência?
-- Atende: KPI3
SELECT @data_referencia AS data_referencia,SUM(r.valor) AS valor_vencido,SUM(CASE WHEN p.id_pagamento IS NULL OR p.data_pagamento>@data_referencia THEN r.valor ELSE 0 END) AS valor_em_aberto,ROUND(100.0*SUM(CASE WHEN p.id_pagamento IS NULL OR p.data_pagamento>@data_referencia THEN r.valor ELSE 0 END)/NULLIF(SUM(r.valor),0),2) AS percentual_em_aberto FROM parcela r LEFT JOIN pagamento p ON p.id_parcela=r.id_parcela WHERE r.data_vencimento<@data_referencia;

-- G09 - Quantas apólices iniciaram vigência e qual o valor médio de suas propostas por mês?
-- Atende: KPI4; KPI5
SELECT DATE_FORMAT(a.inicio_vigencia,'%Y-%m') AS mes,COUNT(*) AS apolices,ROUND(AVG(p.valor_proposta),2) AS valor_medio_proposta FROM apolice a JOIN proposta p ON p.id_proposta=a.id_proposta WHERE a.inicio_vigencia>=@inicio AND a.inicio_vigencia<@fim_exclusivo GROUP BY mes ORDER BY mes;

-- G10 - Quantas renovações concluídas foram registradas por mês?
-- Atende: KPI6
SELECT DATE_FORMAT(data_renovacao,'%Y-%m') AS mes,COUNT(*) AS renovacoes FROM renovacao WHERE data_renovacao>=@inicio AND data_renovacao<@fim_exclusivo GROUP BY mes ORDER BY mes;

-- A01 - Existem CPFs duplicados?
-- Verifica: RN02
SELECT cpf,COUNT(*) AS quantidade FROM cliente GROUP BY cpf HAVING COUNT(*)>1;

-- A02 - Existe proposta vinculada a mais de uma apólice?
-- Verifica: RN21
SELECT id_proposta,COUNT(*) AS quantidade FROM apolice GROUP BY id_proposta HAVING COUNT(*)>1;

-- A03 - Existe parcela com mais de um pagamento?
-- Verifica: RN14
SELECT id_parcela,COUNT(*) AS quantidade FROM pagamento GROUP BY id_parcela HAVING COUNT(*)>1;

-- A04 - Existem parcelas cujo status contradiz a existência de pagamento?
-- Verifica: RN14; RN23
SELECT r.id_parcela,r.status,p.id_pagamento FROM parcela r LEFT JOIN pagamento p ON p.id_parcela=r.id_parcela WHERE (r.status='Paga' AND p.id_pagamento IS NULL) OR (r.status='Pendente' AND p.id_pagamento IS NOT NULL);

-- A05 - Existe sinistro fora da vigência informada?
-- Verifica: RN15
SELECT s.id_sinistro,a.numero_apolice,s.data_sinistro,a.inicio_vigencia,a.fim_vigencia FROM sinistro s JOIN apolice a ON a.id_apolice=s.id_apolice WHERE s.data_sinistro<a.inicio_vigencia OR s.data_sinistro>a.fim_vigencia;

-- A06 - Existem renovações sem data de conclusão ou sem apólice válida?
-- Verifica: RN19
SELECT r.id_renovacao FROM renovacao r LEFT JOIN apolice a ON a.id_apolice=r.id_apolice WHERE r.data_renovacao IS NULL OR a.id_apolice IS NULL;

-- A07 - Existem números de parcela repetidos na mesma apólice?
-- Verifica: RN22
SELECT id_apolice,numero_parcela,COUNT(*) AS quantidade FROM parcela GROUP BY id_apolice,numero_parcela HAVING COUNT(*)>1;

-- A08 - Existem períodos de vigência inválidos?
-- Verifica: RN11
SELECT id_apolice,inicio_vigencia,fim_vigencia FROM apolice WHERE inicio_vigencia>=fim_vigencia;
